import type { ImgHTMLAttributes } from 'react';
import { IMAGE_MANIFEST } from '@/lib/imageManifest';
import { optimizedImageUrl } from '@/lib/image';
import { GEN_BASE as BASE } from '@/lib/productImages';

interface Props extends Omit<ImgHTMLAttributes<HTMLImageElement>, 'src' | 'width' | 'height'> {
  /** A key in IMAGE_MANIFEST (e.g. "ginger-fizz", "life-cheers"). */
  name?: string;
  /** Fallback URL for images outside the manifest (Stripe/Cloudinary). */
  src?: string;
  alt: string;
  /** CSS sizes hint, e.g. "(min-width: 768px) 50vw, 100vw". */
  sizes?: string;
  /** Above-the-fold: load eagerly at high priority. */
  priority?: boolean;
}

/**
 * AVIF/WebP <picture> with a width-based srcset and intrinsic width/height (so
 * nothing shifts while it loads). Falls back to a plain <img> for images that
 * aren't generated by scripts/build-images.mjs (e.g. equipment on Cloudinary).
 */
export default function ResponsiveImage({ name, src, alt, sizes = '100vw', priority = false, className, ...rest }: Props) {
  const entry = name ? IMAGE_MANIFEST[name] : undefined;
  const loading = priority ? 'eager' : 'lazy';
  const fetchPriority = priority ? 'high' : undefined;

  if (!entry || !name) {
    return (
      <img
        src={src ? optimizedImageUrl(src, 1200) : ''}
        alt={alt}
        loading={loading}
        fetchPriority={fetchPriority}
        decoding="async"
        className={className}
        {...rest}
      />
    );
  }

  const set = (ext: string) => entry.widths.map((w) => `${BASE}/${name}-${w}.${ext} ${w}w`).join(', ');
  const fallbackW = entry.widths.find((w) => w >= 800) ?? entry.widths.at(-1)!;

  return (
    // display: contents, so the <img> lays out as if <picture> weren't there
    // (percentage heights, flex and absolute positioning all just work).
    <picture className="contents">
      <source type="image/avif" srcSet={set('avif')} sizes={sizes} />
      <source type="image/webp" srcSet={set('webp')} sizes={sizes} />
      <img
        src={`${BASE}/${name}-${fallbackW}.webp`}
        alt={alt}
        width={entry.w}
        height={entry.h}
        loading={loading}
        fetchPriority={fetchPriority}
        decoding={priority ? 'sync' : 'async'}
        className={className}
        {...rest}
      />
    </picture>
  );
}
